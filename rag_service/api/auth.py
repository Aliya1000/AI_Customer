import logging
import re
from typing import Optional
from fastapi import Header, HTTPException, status
import httpx

from ..config import settings

logger = logging.getLogger("rag_service.api.auth")


async def verify_session_id(
    x_session_id: Optional[str] = Header(None, alias="X-Session-ID"),
    x_internal_secret: Optional[str] = Header(None, alias="X-Internal-Secret"),
) -> str:
    """
    Validates and verifies that the incoming RAG request is authenticated and
    tied to a legitimate active session generated by the backend API.
    """
    if not x_session_id:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Missing 'X-Session-ID' header. Communication with RAG service requires a session ID generated by the backend.",
        )

    clean_sid = x_session_id.strip()

    # 1. System administrative override for global knowledge uploads
    if clean_sid.upper() == "SYSTEM":
        if x_internal_secret and x_internal_secret == settings.rag_internal_secret:
            return "SYSTEM"
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="SYSTEM administrative session access requires a valid 'X-Internal-Secret' header.",
        )

    # 2. Basic structural validation of Backend-generated Session IDs (e.g., SES-...)
    if not clean_sid.startswith("SES-"):
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"Malformed session ID '{clean_sid}'. Expected format 'SES-...'.",
        )

    # 3. Remote Backend Verification Call
    if settings.verify_sessions_with_backend and settings.backend_url:
        verify_url = f"{settings.backend_url.rstrip('/')}/api/sessions/{clean_sid}/verify"
        try:
            async with httpx.AsyncClient(timeout=3.5) as client:
                res = await client.get(verify_url)
                if res.status_code == 200:
                    data = res.json()
                    if data.get("valid"):
                        logger.info(f"Session '{clean_sid}' successfully verified against backend.")
                        return clean_sid
                elif res.status_code == 404:
                    logger.warning(f"Session '{clean_sid}' rejected: not found in backend.")
                    raise HTTPException(
                        status_code=status.HTTP_403_FORBIDDEN,
                        detail=f"Session verification failed: '{clean_sid}' was not found or is inactive in the backend.",
                    )
        except httpx.RequestError as exc:
            # If backend is temporarily unreachable during isolated microservice startup or testing:
            logger.warning(
                f"Backend verification unreachable for session '{clean_sid}' ({exc}); validating format and internal secret."
            )
            if x_internal_secret == settings.rag_internal_secret or not settings.verify_sessions_with_backend:
                return clean_sid

    return clean_sid
