import logging
from typing import Any, Dict, List, Optional, Tuple
import httpx

try:
    from backend.app.config import get_settings
except ImportError:
    from app.config import get_settings

logger = logging.getLogger("backend.app.services.rag_client")


class RAGServiceClient:
    """
    HTTP Client managing communication between the FastAPI Backend and the
    standalone Pinecone Hybrid RAG Microservice (running on port 8001).

    All communication transmits and verifies the session_id generated by the backend.
    """

    def __init__(
        self,
        base_url: Optional[str] = None,
        internal_secret: Optional[str] = None,
        timeout: float = 20.0,
    ):
        settings = get_settings()
        self.base_url = (base_url or settings.rag_service_url).rstrip("/")
        self.internal_secret = internal_secret or settings.rag_internal_secret
        self.timeout = timeout

    def _headers(self, session_id: str) -> Dict[str, str]:
        headers = {
            "X-Session-ID": session_id,
            "X-Internal-Secret": self.internal_secret,
        }
        return headers

    async def retrieve_relevant_information(
        self,
        query: str,
        session_id: str,
        top_k: int = 5,
        alpha: float = 0.5,
    ) -> List[Dict[str, Any]]:
        """
        Calls RAG microservice: POST /api/v1/documents/retrieve
        Transmits backend-generated session_id for verification.
        """
        url = f"{self.base_url}/api/v1/documents/retrieve"
        headers = self._headers(session_id)
        payload = {
            "query": query,
            "session_id": session_id,
            "top_k": top_k,
            "alpha": alpha,
            "rewrite_query": True,
        }

        try:
            async with httpx.AsyncClient(timeout=self.timeout) as client:
                res = await client.post(url, json=payload, headers=headers)
                if res.status_code == 200:
                    data = res.json()
                    chunks = data.get("chunks", [])
                    logger.info(
                        f"Retrieved {len(chunks)} chunks from RAG service for session '{session_id}'"
                    )
                    return chunks
                else:
                    logger.warning(
                        f"RAG service returned status {res.status_code} for session '{session_id}': {res.text}"
                    )
                    return []
        except Exception as e:
            logger.warning(
                f"RAG service call to '{url}' failed for session '{session_id}' ({e}); proceeding with local context."
            )
            return []

    async def ingest_uploaded_files(
        self,
        files: List[Tuple[str, bytes]],
        session_id: str = "SYSTEM",
    ) -> Dict[str, Any]:
        """
        Calls RAG microservice: POST /api/v1/documents/upload
        """
        url = f"{self.base_url}/api/v1/documents/upload"
        headers = {
            "X-Session-ID": session_id,
            "X-Internal-Secret": self.internal_secret,
        }

        multipart_files = [
            ("files", (filename, content, "application/octet-stream"))
            for filename, content in files
        ]

        try:
            async with httpx.AsyncClient(timeout=60.0) as client:
                res = await client.post(url, files=multipart_files, headers=headers)
                if res.status_code in (200, 201):
                    return res.json()
                logger.warning(f"RAG document upload failed: {res.status_code} - {res.text}")
                return {"success": False, "message": res.text, "documents_processed": 0}
        except Exception as e:
            logger.warning(f"RAG microservice upload error ({e})")
            return {"success": False, "message": str(e), "documents_processed": 0}

    async def diagnose_image(
        self,
        file_bytes: bytes,
        filename: str,
        session_id: str,
        notes: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Calls RAG microservice: POST /api/v1/multimodal/diagnose
        """
        url = f"{self.base_url}/api/v1/multimodal/diagnose"
        headers = self._headers(session_id)
        files = {"file": (filename, file_bytes, "image/png")}
        data = {"notes": notes or ""}

        try:
            async with httpx.AsyncClient(timeout=10.0) as client:
                res = await client.post(url, files=files, data=data, headers=headers)
                if res.status_code == 200:
                    return res.json()
                logger.warning(f"RAG image diagnosis returned {res.status_code}: {res.text}")
        except Exception as e:
            logger.warning(f"RAG microservice diagnosis error ({e})")

        return {
            "session_id": session_id,
            "filename": filename,
            "notes": notes,
            "extracted_text": f"Visual defect analysis note for {filename}: {notes or 'No critical defect observed.'}",
            "status": "diagnosed_fallback"
        }

    async def get_health(self) -> Dict[str, Any]:
        """
        Calls RAG microservice: GET /api/v1/health
        """
        url = f"{self.base_url}/api/v1/health"
        try:
            async with httpx.AsyncClient(timeout=2.5) as client:
                res = await client.get(url)
                if res.status_code == 200:
                    return res.json()
        except Exception:
            pass
        return {"status": "unreachable", "url": self.base_url}
