from typing import List
from fastapi import APIRouter, Depends, HTTPException, status

try:
    from backend.app.schemas.session import SessionCreate, SessionResponse, SessionUpdate
    from backend.app.services.session_service import SessionService
except ImportError:
    from app.schemas.session import SessionCreate, SessionResponse, SessionUpdate
    from app.services.session_service import SessionService

router = APIRouter(tags=["Sessions"])


def get_session_service() -> SessionService:
    return SessionService()


@router.post(
    "/sessions",
    status_code=status.HTTP_201_CREATED,
    response_model=SessionResponse,
    summary="Create a new session",
)
@router.post(
    "/sessions/",
    status_code=status.HTTP_201_CREATED,
    response_model=SessionResponse,
    include_in_schema=False,
)
def create_session(
    payload: SessionCreate,
    service: SessionService = Depends(get_session_service),
) -> SessionResponse:
    return service.create_session(payload)


@router.get(
    "/sessions",
    status_code=status.HTTP_200_OK,
    response_model=List[SessionResponse],
    summary="List all sessions",
)
@router.get(
    "/sessions/",
    status_code=status.HTTP_200_OK,
    response_model=List[SessionResponse],
    include_in_schema=False,
)
def list_sessions(
    limit: int = 100,
    service: SessionService = Depends(get_session_service),
) -> List[SessionResponse]:
    return service.list_sessions(limit=limit)


@router.get(
    "/sessions/{session_id}",
    status_code=status.HTTP_200_OK,
    response_model=SessionResponse,
    summary="Retrieve session details with agent outputs",
)
@router.get(
    "/sessions/{session_id}/",
    status_code=status.HTTP_200_OK,
    response_model=SessionResponse,
    include_in_schema=False,
)
async def get_session(
    session_id: str,
    service: SessionService = Depends(get_session_service),
) -> SessionResponse:
    return await service.get_session(session_id)


@router.patch(
    "/sessions/{session_id}",
    status_code=status.HTTP_200_OK,
    response_model=SessionResponse,
    summary="Update session fields",
)
def update_session(
    session_id: str,
    payload: SessionUpdate,
    service: SessionService = Depends(get_session_service),
) -> SessionResponse:
    return service.update_session(session_id, payload)


@router.get(
    "/sessions/{session_id}/verify",
    status_code=status.HTTP_200_OK,
    summary="Verify if a session ID is valid, active, and generated by the backend",
)
def verify_session(
    session_id: str,
    service: SessionService = Depends(get_session_service),
):
    session = service.session_repo.get_session(session_id)
    if not session:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Session '{session_id}' not found or invalid",
        )
    return {
        "valid": True,
        "session_id": session_id,
        "status": session.get("status", "active"),
        "interaction_mode": session.get("interaction_mode"),
        "product_name": session.get("product_name"),
    }
